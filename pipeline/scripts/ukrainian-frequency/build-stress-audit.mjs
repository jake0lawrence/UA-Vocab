#!/usr/bin/env node
// ============================================================
// UKRAINIAN FREQUENCY : thread 07, word stress: draw the audit sample
//
// Builds the stress column exactly as build-stress.mjs does, draws the
// pre-registered stratified sample with the seed below, and writes it to
// src/data/ukrainian-frequency/stress-audit-sample.json. The sample is drawn
// once and committed; --check re-derives it and fails on any difference, so a
// changed column or a changed seed cannot quietly move the sample under the
// reviewers. The reviews themselves come back through the Validation Desk
// (kind stress.verdict, npm run validate:export) as stress-audit-reviews.json.
//
//   node scripts/ukrainian-frequency/build-stress-audit.mjs [--check]
//
// House rule: no em-dashes.
// ============================================================

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { drawSample, auditSummary, AUDIT_VERSION, TARGET, MIN_REVIEWED } from "../../src/lib/ukrainian-frequency/stress-audit.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DATA = path.join(ROOT, "src", "data", "ukrainian-frequency");
const DL = path.join(ROOT, "public", "downloads", "ukrainian-frequency");
const OUT = path.join(DATA, "stress-audit-sample.json");
const REVIEWS = path.join(DATA, "stress-audit-reviews.json");
const TIER = path.join(ROOT, "src", "lib", "ukrainian-frequency", "stress-audit.data.mjs");

// The seed is the pre-registration: the date the design was fixed and the
// column version it was drawn over. Changing either is a new audit. The
// column is pinned here, not read from STRESS_VERSION: a later release with
// byte-identical rows (v1.0.1 corrected a credit in the README) must not
// redraw a sample that reviewers have already judged. The tier carries the
// hash of the rows the sample was drawn over, and the page's live check
// compares that hash to the current release's.
export const AUDIT_COLUMN = "v1.0.0";
export const SEED = `stress-audit ${AUDIT_VERSION} 2026-10-02 over stress ${AUDIT_COLUMN}`;

function main() {
  const check = process.argv.includes("--check");
  // Drawn over the frozen release the audit was registered against, never the
  // live column: a later correction to the column (a ledger row, a new
  // version) must not redraw a pre-registered sample.
  const { rows } = JSON.parse(readFileSync(path.join(DL, "stress", AUDIT_COLUMN, "stress.json"), "utf8"));

  const sample = drawSample(rows, { seed: SEED });
  const out = {
    note: "The pre-registered accuracy audit of the stress column: a seeded, stratified random sample of in-scope rows, drawn once by scripts/ukrainian-frequency/build-stress-audit.mjs and never redrawn; each row is a Validation Desk task (stress.verdict) and the accepted verdicts come back as stress-audit-reviews.json. Design and criterion: docs/ukrainian-frequency/stress-audit.md.",
    version: AUDIT_VERSION,
    column: AUDIT_COLUMN,
    drawn: "2026-10-02",
    seed: sample.seed,
    sizes: sample.sizes,
    counts: sample.counts,
    items: sample.items,
  };
  const text = JSON.stringify(out, null, 1) + "\n";

  // The browser tier: the design and the current summary, never the items
  // (the sample stays a data file; the page shows the rule and the count).
  const reviews = JSON.parse(readFileSync(REVIEWS, "utf8"));
  const summary = auditSummary(out, reviews.reviews || []);
  const tier = {
    version: AUDIT_VERSION,
    column: AUDIT_COLUMN,
    columnSha256: createHash("sha256").update(readFileSync(path.join(DL, "stress", AUDIT_COLUMN, "stress.csv"))).digest("hex"),
    drawn: out.drawn,
    seed: out.seed,
    items: out.items.length,
    counts: out.counts,
    criterion: { target: TARGET, minReviewed: MIN_REVIEWED },
    reviewsGeneratedAt: reviews.generatedAt || null,
    summary,
  };
  const tierText =
    "// GENERATED by scripts/ukrainian-frequency/build-stress-audit.mjs - do not edit by hand.\n" +
    "// The stress accuracy audit as the page reads it: the pre-registered design, the\n" +
    "// sample's counts and the summary re-derived from the committed reviews.\n" +
    `export const STRESS_AUDIT = ${JSON.stringify(tier, null, 2)};\n`;

  if (check) {
    const cur = readFileSync(OUT, "utf8");
    if (cur !== text) {
      console.error("stress audit sample: the committed sample does not re-derive from the column and the seed");
      process.exit(1);
    }
    if (readFileSync(TIER, "utf8") !== tierText) {
      console.error("stress audit tier: stress-audit.data.mjs does not re-derive from the sample and the reviews");
      process.exit(1);
    }
    console.log(`stress audit sample verified: ${out.items.length} items across ${Object.keys(out.counts).length} strata; ${summary.reviewed} reviewed, ${summary.verdict}`);
    return;
  }
  writeFileSync(OUT, text);
  writeFileSync(TIER, tierText);
  for (const [id, c] of Object.entries(out.counts)) console.log(`  ${id}: ${c.drawn} of ${c.pool}${c.census ? " (census)" : ""}`);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${out.items.length} items`);
}

// Only when run as a script: the test imports SEED from this module, and an
// unguarded main() once rewrote the committed sample on import.
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) main();

// ---------------------------------------------------------------------------
// Ukrainian Frequency - freeze the vocabulary-size self-test item bank (thread
// 05). No network.
//
// Runs the deterministic item-bank builder (60 real lemmas + 60 constructed
// pseudowords, stratified across the 12 thousand-rank frequency bands) and
// writes the public download bundle to
// public/downloads/ukrainian-frequency/vocab-test/<version>/ (items.json, a
// manifest, SHA256SUMS, an index page), and regenerates the committed,
// browser-safe tier at src/lib/ukrainian-frequency/vocab-test.data.mjs (the
// item bank the in-browser test renders), which re-derives from the same
// thread-01 seed.
//
//   node scripts/ukrainian-frequency/build-vocab-test.mjs
//   node scripts/ukrainian-frequency/build-vocab-test.mjs --check   (verify, no writes)
// ---------------------------------------------------------------------------

import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildVocabTest,
  BAND_COUNT,
  REAL_PER_BAND,
  PSEUDO_PER_BAND,
} from "../../src/lib/ukrainian-frequency/vocab-test-release.mjs";
import { renderReleaseIndex } from "./lib/release-index.mjs";

const CHECK = process.argv.includes("--check");

const VERSION = "v1.2.0";
const LICENSE = "CC-BY-4.0";
const DATASET = "ukrainian-frequency-vocab-test";
const CITATION =
  `Lawrence, J. (2026). Ukrainian Frequency: a self-scoring vocabulary-size test (${VERSION}). jakelawrence.xyz/research/ukrainian-frequency/vocab-test. Item bank drawn from the Ukrainian Frequency lemma list, itself derived from UberText 2.0 (Chaplynskyi, 2023).`;

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "public", "downloads", "ukrainian-frequency", "vocab-test", VERSION);
const LATEST_DIR = path.join(ROOT, "public", "downloads", "ukrainian-frequency", "vocab-test");
const LIB = path.join(ROOT, "src", "lib", "ukrainian-frequency");

const sha256 = (body) => createHash("sha256").update(body).digest("hex");

function main() {
  const items = buildVocabTest();
  const realCount = items.filter((it) => it.isReal).length;
  const pseudoCount = items.length - realCount;

  const itemsBody = JSON.stringify(items) + "\n";
  const sha = { "items.json": sha256(itemsBody) };

  const manifest = {
    version: VERSION,
    dataset: DATASET,
    subject: "A self-scoring Yes/No vocabulary-size test for modern Ukrainian, drawn from the Ukrainian Frequency lemma list",
    tier: "public",
    method:
      "60 real lemmas and 60 constructed pseudowords, 5 of each per thousand-rank frequency band (12 bands, top 12000 lemmas). Each pseudoword is a real lemma from elsewhere in the same band with one deterministic phonological letter substitution, kept only if it collides with none of the 12000-lemma list, another generated pseudoword, or a 333k-headword reference Ukrainian dictionary (dict_uk / LibreOffice dictionaries, MPL-1.1) checked at build time, and never built from a lemma that is also asked as a real item in any band (v1.2.0; v1.1.0 let one spelling listed at two ranks leak). This is a constructed instrument; it has not been independently validated against a psycholinguistic norming study.",
    canonical: "/research/ukrainian-frequency/vocab-test",
    bandCount: BAND_COUNT,
    realPerBand: REAL_PER_BAND,
    pseudoPerBand: PSEUDO_PER_BAND,
    itemCount: items.length,
    realCount,
    pseudoCount,
    license: LICENSE,
    files: [{ file: "items.json", about: "The full item bank: id, form, isReal, band, and (real items) source rank or (pseudowords) source lemma and rank." }],
    citation: CITATION,
    sha256: sha,
  };

  const manifestBody = JSON.stringify(manifest, null, 2) + "\n";
  const sumsBody = `${sha["items.json"]}  items.json\n`;
  const latestBody = JSON.stringify({ latest: VERSION, path: `/downloads/ukrainian-frequency/vocab-test/${VERSION}/` }, null, 2) + "\n";

  const dataBody =
    "// GENERATED by scripts/ukrainian-frequency/build-vocab-test.mjs - do not edit by hand.\n" +
    "// The browser-safe vocabulary-size test item bank (thread 05): 60 real lemmas\n" +
    "// plus 60 constructed pseudowords, stratified across the 12 thousand-rank\n" +
    "// frequency bands. Re-derives from the committed thread-01 seed; the build\n" +
    "// script's --check mode verifies byte-for-byte reproduction.\n" +
    "export const VOCAB_TEST = " +
    JSON.stringify(
      {
        version: VERSION,
        dataset: DATASET,
        license: LICENSE,
        citation: CITATION,
        bandCount: BAND_COUNT,
        realPerBand: REAL_PER_BAND,
        pseudoPerBand: PSEUDO_PER_BAND,
        itemCount: items.length,
        realCount,
        pseudoCount,
        items,
        files: ["items.json"],
        sha256: sha,
        downloadBase: `/downloads/ukrainian-frequency/vocab-test/${VERSION}`,
      },
      null,
      2,
    ) +
    ";\n";

  if (CHECK) {
    const committed = readFileSync(path.join(LIB, "vocab-test.data.mjs"), "utf8");
    if (committed !== dataBody) {
      console.error("DRIFT: src/lib/ukrainian-frequency/vocab-test.data.mjs does not match a fresh build. Run `npm run uk-freq:build-vocab-test`.");
      process.exit(1);
    }
    const committedManifest = readFileSync(path.join(OUT, "manifest.json"), "utf8");
    if (committedManifest !== manifestBody) {
      console.error("DRIFT: committed vocab-test manifest.json does not match a fresh build. Run `npm run uk-freq:build-vocab-test`.");
      process.exit(1);
    }
    console.log("Ukrainian Frequency vocab-test verified: committed tier re-derives byte-for-byte.");
    return;
  }

  const indexBody = renderReleaseIndex({
    kicker: "Open data / Ukrainian Frequency",
    title: "A Ukrainian vocabulary-size self-test item bank",
    subject: manifest.subject,
    version: VERSION,
    license: LICENSE,
    canonical: "/research/ukrainian-frequency/vocab-test",
    citation: CITATION,
    files: ["items.json"],
  });

  mkdirSync(OUT, { recursive: true });
  writeFileSync(path.join(OUT, "items.json"), itemsBody);
  writeFileSync(path.join(OUT, "manifest.json"), manifestBody);
  writeFileSync(path.join(OUT, "SHA256SUMS"), sumsBody);
  writeFileSync(path.join(OUT, "index.html"), indexBody);
  writeFileSync(path.join(LATEST_DIR, "latest.json"), latestBody);
  writeFileSync(path.join(LIB, "vocab-test.data.mjs"), dataBody);

  console.log("Ukrainian Frequency vocab-test frozen:", VERSION);
  console.log(`  items ${items.length} (${realCount} real, ${pseudoCount} pseudo) | bands ${BAND_COUNT} | license ${LICENSE}`);
}

main();

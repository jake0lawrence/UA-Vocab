#!/usr/bin/env node
// Freeze the dictionary's third reading of the stress column.
//
//   node scripts/ukrainian-frequency/build-dictionary.mjs          # write
//   node scripts/ukrainian-frequency/build-dictionary.mjs --check  # drift gate
//
// Reads the committed dmklinger/ukrainian snapshot and the stress release,
// scores every covered polysyllabic row (agree / agree on a variant /
// disagree), and writes the browser-safe tier the lookup page renders:
// the counts, the disagreement rows and the snapshot's provenance. The test
// re-derives the same counts from the same inputs with the pure builder.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildDictionaryStats } from "../../src/lib/ukrainian-frequency/dictionary.mjs";
import { STRESS_VERSION } from "../../src/lib/ukrainian-frequency/stress.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "src/lib/ukrainian-frequency/dictionary.data.mjs");

export const DICTIONARY_TIER_VERSION = "v1";

export function buildDictionaryTier() {
  const snapshot = JSON.parse(fs.readFileSync(path.join(ROOT, "src/data/ukrainian-frequency/dmk-dictionary.json"), "utf8"));
  const release = JSON.parse(fs.readFileSync(path.join(ROOT, "public/downloads/ukrainian-frequency/stress", STRESS_VERSION, "stress.json"), "utf8"));
  const stats = buildDictionaryStats(snapshot, release.rows);
  const { disagreements, ...counts } = stats;
  return {
    version: DICTIONARY_TIER_VERSION,
    column: release.version,
    source: snapshot.source,
    kept: snapshot.kept,
    stats: counts,
    disagreements,
  };
}

function render(tier) {
  return (
    "// GENERATED by scripts/ukrainian-frequency/build-dictionary.mjs - do not edit by hand.\n" +
    "// The dmklinger/ukrainian dictionary (CC BY-SA 3.0) read against the stress\n" +
    "// column: coverage of the list, agreement on every covered polysyllable,\n" +
    "// and each disagreement as a row. Re-derived in CI from the snapshot and the\n" +
    "// release by dictionary.test.js; the build script's --check mode verifies\n" +
    "// byte-for-byte reproduction.\n" +
    `export const DICTIONARY = ${JSON.stringify(tier, null, 1)};\n`
  );
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const body = render(buildDictionaryTier());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== body) {
      console.error("dictionary.data.mjs is stale: run `npm run uk-freq:build-dictionary`");
      process.exit(1);
    }
    console.log("dictionary.data.mjs reproduces byte for byte");
  } else {
    fs.writeFileSync(OUT, body);
    const t = JSON.parse(body.slice(body.indexOf("{"), body.lastIndexOf("}") + 1));
    console.log(`dictionary.data.mjs: ${t.stats.covered} covered, ${t.stats.agree + t.stats.agreeVariant} agree of ${t.stats.compared} compared, ${t.stats.disagree} disagree`);
  }
}

def sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    with open(path, encoding="utf-8", newline="") as fh:
        header = next(csv.reader(fh))
    return header, rows


def to_table(header, rows, types):
    cols = {}
    for name in header:
        t = types.get(name)
        vals = [r[name] for r in rows]
        if t == INT:
            cols[name] = pa.array([int(v) if v != "" else None for v in vals], type=pa.int64())
        elif t == FLOAT:
            cols[name] = pa.array([float(v) if v != "" else None for v in vals], type=pa.float64())
        elif t == BOOL:
            out = []
            for v in vals:
                if v == "":
                    out.append(None)
                elif v in ("yes", "true", "1"):
                    out.append(True)
                elif v in ("no", "false", "0"):
                    out.append(False)
                else:
                    raise ValueError(f"unexpected boolean {v!r} in column {name}")
            cols[name] = pa.array(out, type=pa.bool_())
        else:
            cols[name] = pa.array([v if v != "" else None for v in vals], type=pa.string())
    return pa.table(cols)


def parquet_bytes(table):
    """Deterministic bytes: no timestamps or creator metadata beyond pyarrow's
    fixed strings, so the same rows hash the same across builds."""
    buf = io.BytesIO()
    pq.write_table(table, buf, compression="zstd", write_statistics=True)
    return buf.getvalue()


def build():
    registry = json.load(open(REGISTRY, encoding="utf-8"))
    datasets = {}
    outputs = {}
    for d in DATASETS:
        src_path = os.path.join(DL, d["source"])
        src_bytes = open(src_path, "rb").read()
        header, rows = read_csv(src_path)
        table = to_table(header, rows, d["types"])
        body = parquet_bytes(table)
        outputs[d["file"]] = body
        dep = registry["deposits"].get(d["deposit"]) if d["deposit"] else None
        datasets[d["name"]] = {
            "file": d["file"],
            "rows": table.num_rows,
            "columns": header,
            "source": {"path": "public/downloads/ukrainian-frequency/" + d["source"], "sha256": sha256_bytes(src_bytes), "rows": len(rows)},
            "sha256": sha256_bytes(body),
            "version": d["version"],
            "snapshot": d["snapshot"],
            "license": d["license"],
            "title": d["title"],
            "description": d["description"],
            "attribution": d["attribution"],
            "citation": d["citation"],
            "url": d["url"],
            "conceptDoi": dep["conceptDoi"] if dep else None,
        }
    manifest = {
        "package": "uavocab",
        "packageVersion": PACKAGE_VERSION,
        # Layout-neutral on purpose: both checkouts write this same manifest.
        "generatedBy": "build-package.py (scripts/build-package.py in https://github.com/jake0lawrence/UA-Vocab), from the release files under downloads/ukrainian-frequency",
        "site": SITE,
        "combinedLicense": COMBINED_LICENSE,
        "combinedLicenseWhy": COMBINED_WHY,
        "notShipped": NOT_SHIPPED,
        "datasets": datasets,
    }
    outputs["manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    return outputs, manifest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="rebuild in memory and fail on any drift from the committed data tier")
    args = ap.parse_args()
    outputs, manifest = build()
    if args.check:
        drift = []
        for name, body in outputs.items():
            path = os.path.join(OUT, name)
            if not os.path.exists(path) or open(path, "rb").read() != body:
                drift.append(name)
        if drift:
            print("uavocab data tier is stale; rebuild with scripts/ukrainian-frequency/build-package.py:", ", ".join(drift))
            sys.exit(1)
        print(f"uavocab data tier matches the published files ({len(manifest['datasets'])} datasets)")
        return
    os.makedirs(OUT, exist_ok=True)
    for name, body in outputs.items():
        with open(os.path.join(OUT, name), "wb") as fh:
            fh.write(body)
    for name, d in manifest["datasets"].items():
        print(f"{name:18s} {d['rows']:6d} rows  {d['license']:14s} {d['file']}")
    total = sum(len(b) for b in outputs.values())
    print(f"wrote {len(outputs)} files, {total / 1024:.0f} KB, package {PACKAGE_VERSION}, combined license {COMBINED_LICENSE}")


if __name__ == "__main__":
    main()

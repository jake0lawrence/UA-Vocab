def _layout():
    """Where things are. The same script runs in two checkouts and must write
    the same bytes in both:

      the study's source repository: scripts/ukrainian-frequency/build-package.py,
        releases in public/downloads/ukrainian-frequency, the package in
        packages/uavocab, the DOI registry in src/data/ukrainian-frequency;
      the open repository (github.com/jake0lawrence/UA-Vocab, generated by
        scripts/uavocab/build-open-repo.mjs): scripts/build-package.py, releases
        in downloads/ukrainian-frequency (the path uavocab.org serves them at),
        the package in python/uavocab, the registry in registry/zenodo.json.
    """
    mono = os.path.abspath(os.path.join(HERE, "..", ".."))
    if os.path.isdir(os.path.join(mono, "public", "downloads", "ukrainian-frequency")):
        return (os.path.join(mono, "public", "downloads", "ukrainian-frequency"),
                os.path.join(mono, "packages", "uavocab"),
                os.path.join(mono, "src", "data", "ukrainian-frequency", "zenodo.json"))
    repo = os.path.abspath(os.path.join(HERE, ".."))
    return (os.path.join(repo, "downloads", "ukrainian-frequency"),
            os.path.join(repo, "python", "uavocab"),
            os.path.join(repo, "registry", "zenodo.json"))



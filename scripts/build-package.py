#!/usr/bin/env python3
# ---------------------------------------------------------------------------
# Ukrainian Frequency: build the data tier of the `uavocab` Python package
# (published as ukvocab up to 0.4.1; renamed 2026-11-15 to match uavocab.org).
#
# Reads the PUBLISHED download files under public/downloads/ukrainian-frequency
# (never the seed sources, so a package row count is a published row count) and
# writes them as Parquet into packages/uavocab/src/uavocab/data/, with a
# manifest that records, per dataset: the source file and its SHA-256, the
# output file and its SHA-256, the row count, the columns, the license, the
# snapshot date, the attribution and the citation. Everything the package's
# sources() returns comes from that manifest; nothing in the package is typed by
# hand.
#
# What ships, and what does not (infrastructure work order WO-1):
#   ships:   the top-12,000 lemma list with ranks; the PULS CEFR overlay
#            (validated levels only); the Borodin A1 and A2 minimums; the
#            crosswalk; the B1 enrichment tables (aspect relations, government,
#            collocations); the word-stress column (thread 07)
#   does not: predicted levels (a separate file on the site, never merged),
#            VESUM-derived wordform or lexicon data, anything under a
#            NonCommercial license (the UniMorph family ids are a modeling
#            input, not data), the Wikipedia example sentences
#
# Run: python3 scripts/ukrainian-frequency/build-package.py   (needs pyarrow)
# Check: python3 scripts/ukrainian-frequency/build-package.py --check
# In the open repository the same file is scripts/build-package.py and reads
# downloads/ukrainian-frequency; the bytes it writes are the same (see _layout).
# The `source.path` it records is the release file's logical id,
# public/downloads/ukrainian-frequency/<file>, in both checkouts; strip
# "public" and it is the address uavocab.org serves the file at.
#        (rebuilds in memory and fails if any output or source hash moved)
#
# House rule: no em dashes in the files this writes.
# ---------------------------------------------------------------------------


"""Lazy, read-only access to the package's Parquet data tier.

Nothing is read at import time. Each table loads on first use through
pyarrow, and the lookup indexes are built once per process. The manifest
(manifest.json, generated by scripts/build-package.py in
https://github.com/jake0lawrence/UA-Vocab from the published release files) is the only description of the data; this module
never hard-codes a row count, a license or a snapshot date.
"""

from __future__ import annotations

import json
import os
import unicodedata
from functools import lru_cache
from typing import Dict, List, Optional

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")

LEVELS = ("A1", "A2", "B1", "B2", "C1")
LEVEL_INDEX = {lvl: i for i, lvl in enumerate(LEVELS)}

_APOSTROPHES = ("'", "ʼ", "’", "‘", "ʹ", "`", "´")


def norm(s: str) -> str:
    """The join key used across every table: NFC, the pedagogical stress mark
    (U+0301) stripped, every apostrophe glyph folded to U+2019 (the frequency
    list's glyph), whitespace trimmed, lowercased."""
    s = unicodedata.normalize("NFD", s or "")
    s = "".join(ch for ch in s if ch != "́")
    s = unicodedata.normalize("NFC", s)
    for glyph in _APOSTROPHES:
        s = s.replace(glyph, "’")
    return s.strip().lower()


@lru_cache(maxsize=None)
def manifest() -> dict:
    with open(os.path.join(DATA_DIR, "manifest.json"), encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=None)
def table(name: str):
    """The pyarrow Table for a dataset name from the manifest."""
    import pyarrow.parquet as pq

    meta = manifest()["datasets"][name]
    return pq.read_table(os.path.join(DATA_DIR, meta["file"]))


@lru_cache(maxsize=None)
def rows(name: str) -> List[dict]:
    """The dataset as a list of plain dicts (nulls as None)."""
    return table(name).to_pylist()


def source_of(name: str) -> dict:
    """The provenance stamp every return value carries for a dataset."""
    m = manifest()["datasets"][name]
    return {
        "dataset": name,
        "version": m["version"],
        "snapshot": m["snapshot"],
        "license": m["license"],
        "rows": m["rows"],
        "sha256": m["sha256"],
        "conceptDoi": m.get("conceptDoi"),
    }


# ---------------------------------------------------------------- indexes
@lru_cache(maxsize=None)
def frequency_by_key() -> Dict[str, List[dict]]:
    """norm(lemma) -> frequency rows (rank order); a spelling can have several
    readings because the corpus tagger split it by part of speech."""
    out: Dict[str, List[dict]] = {}
    for r in rows("frequency"):
        out.setdefault(norm(r["lemma"]), []).append(r)
    for v in out.values():
        v.sort(key=lambda r: r["rank"])
    return out


@lru_cache(maxsize=None)
def frequency_by_rank() -> Dict[int, dict]:
    return {r["rank"]: r for r in rows("frequency")}


@lru_cache(maxsize=None)
def level_by_rank() -> Dict[int, dict]:
    """rank -> validated overlay row (level, join)."""
    return {r["rank"]: r for r in rows("validated_cefr")}


@lru_cache(maxsize=None)
def stress_by_rank() -> Dict[int, dict]:
    """rank -> the stress row (stress, variants as a list, status, note, source)."""
    out: Dict[int, dict] = {}
    for r in rows("stress"):
        out[r["rank"]] = {
            "stress": r["stress"] or None,
            "variants": [v for v in (r["stress_variants"] or "").split("|") if v],
            "status": r["stress_status"],
            "note": r["note"] or None,
            "source": r["source"],
        }
    return out


@lru_cache(maxsize=None)
def crosswalk_by_key() -> Dict[str, dict]:
    return {norm(r["lemma"]): r for r in rows("crosswalk")}


@lru_cache(maxsize=None)
def borodin_keys(volume: str) -> Dict[str, List[dict]]:
    """norm(headword lemma) -> the matched entries of a Borodin volume. Only
    matched entries carry a lemma; off-list headwords are reached through the
    crosswalk's volume column instead."""
    name = {"a1": "borodin_a1", "a2": "borodin_a2"}[volume]
    out: Dict[str, List[dict]] = {}
    for r in rows(name):
        if r.get("matched") and r.get("lemma"):
            out.setdefault(norm(r["lemma"]), []).append(r)
    return out


@lru_cache(maxsize=None)
def crosswalk_volume_keys(volume: str) -> frozenset:
    """Every lemma string a Borodin volume carries, on or off the frequency
    list, as the crosswalk records it (a word in both volumes counts as A1)."""
    keys = set()
    for r in rows("crosswalk"):
        v = r.get("volume")
        if v == volume or (volume == "A2" and v == "A1"):
            keys.add(norm(r["lemma"]))
    return frozenset(keys)


@lru_cache(maxsize=None)
def aspect_by_verb() -> Dict[str, List[dict]]:
    out: Dict[str, List[dict]] = {}
    for r in rows("b1_aspect"):
        out.setdefault(norm(r["b1_verb"]), []).append(r)
    return out


@lru_cache(maxsize=None)
def government_by_verb() -> Dict[str, List[dict]]:
    out: Dict[str, List[dict]] = {}
    for r in rows("b1_government"):
        out.setdefault(norm(r["verb"]), []).append(r)
    return out


@lru_cache(maxsize=None)
def collocations_by_lemma() -> Dict[str, List[dict]]:
    out: Dict[str, List[dict]] = {}
    for r in rows("b1_collocations"):
        out.setdefault(norm(r["lemma"]), []).append(r)
    return out


@lru_cache(maxsize=None)
def level_set(level: str) -> frozenset:
    """norm(lemma) of every validated lemma at or below a level."""
    if level not in LEVEL_INDEX:
        raise ValueError(f"unknown level {level!r}; one of {LEVELS}")
    top = LEVEL_INDEX[level]
    by_rank = frequency_by_rank()
    return frozenset(norm(by_rank[r["rank"]]["lemma"]) for r in rows("validated_cefr") if LEVEL_INDEX[r["level"]] <= top)


@lru_cache(maxsize=None)
def top_n_set(n: int) -> frozenset:
    return frozenset(norm(r["lemma"]) for r in rows("frequency") if r["rank"] <= n)


def clear_cache() -> None:
    """Drop every loaded table and index (tests, or long processes that want
    the memory back)."""
    for fn in (manifest, table, rows, frequency_by_key, frequency_by_rank, level_by_rank, crosswalk_by_key, stress_by_rank,
               borodin_keys, crosswalk_volume_keys, aspect_by_verb, government_by_verb, collocations_by_lemma,
               level_set, top_n_set):
        fn.cache_clear()
